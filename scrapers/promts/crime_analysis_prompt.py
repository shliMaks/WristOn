def get_crime_analysis_prompt_web(text: str) -> str:
    prompt = f"""
    Ти — аналітик кримінальних новин. Прочитай текст і витягни геолокацію ГОЛОВНОЇ події, про яку йде мова. 
    Ігноруй будь-які інші адреси.
    Поверни ТІЛЬКИ валідний JSON.
    Формат JSON:
    {{
        "street": "тільки назва вулиці (наприклад: Василя Порика)",
        "district": "район (наприклад: Подільський)",
        "is_outdoor": true або false
    }}
    Якщо вулицю неможливо визначити, поверни null для поля street.
    
    Текст для аналізу:
    {text}
    """

    return prompt