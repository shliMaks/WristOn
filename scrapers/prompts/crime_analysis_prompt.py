from core.config import CATEGORIES


def get_crime_analysis_prompt() -> str:
    categories_text = "\n".join([f'{k}: "{v}"' for k, v in CATEGORIES.items()])

    prompt = f"""
    Ти — аналітик кримінальних новин. Тобі буде надано список пронумерованих текстів (наприклад: "[0] текст...", "[1] текст...").
    Твоя задача — проаналізувати КОЖНИЙ текст окремо і повернути масив результатів у форматі JSON.
    Поверни ТІЛЬКИ валідний масив JSON без жодного додаткового форматування (без Markdown блоків типу ```json).

    Доступні категорії подій (category_id):
    {categories_text}

    Формат ВІДПОВІДІ (масив об'єктів):
    [
        {{
            "original_index": число (індекс тексту, який ти аналізуєш, наприклад 0, 1, 2),
            "category_id": ціле число (вибери з доступних ID). Якщо подія не є злочином/ДТП — null,
            "title": "коротка суть події",
            "street": "тільки назва вулиці. Якщо неможливо визначити — null",
            "district": "район. Якщо неможливо визначити — null",
            "is_outdoor": true або false
        }},
        ... (решта об'єктів для кожного тексту)
    ]
    """
    return prompt
